#!/usr/bin/env bash
# Create clickable Mac apps for the tools in ~/Applications (drag them to the Dock).
#   bin/make_apps.sh
# Re-run after moving the repo. Each app is a tiny shell script inside a .app folder:
#   Rimay Curation   – starts the curation server (port 8765) if needed, opens it
#   Rimay Results    – rebuilds the experiment dashboard, opens it
#   Rimay Anomalies  – rebuilds the Experiment 3 anomaly viewer, opens it
#   Rimay Pragyan    – starts the Pragyan comparison server (port 8766) if needed, opens it
# Servers keep running in the background; clicking again just reopens the page.
# Stop them with: bin/make_apps.sh --stop
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$HOME/Applications"
LOGS="$REPO/outputs/_logs"

if [[ "${1:-}" == "--stop" ]]; then
  for port in 8765 8766; do
    pid="$(lsof -nP -tiTCP:$port -sTCP:LISTEN || true)"
    [[ -n "$pid" ]] && kill $pid && echo "Stopped the server on port $port."
  done
  exit 0
fi

mkdir -p "$DEST" "$LOGS"
ICONS="$(mktemp -d)"

# make_icon <name> <letter> <hex colour>
make_icon() {
  "$REPO/.venv/bin/python" - "$ICONS/$1" "$2" "$3" <<'PY'
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
out, letter, colour = Path(sys.argv[1] + ".iconset"), sys.argv[2], sys.argv[3]
out.mkdir(parents=True, exist_ok=True)
S = 1024
img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
d.rounded_rectangle((100, 100, S - 100, S - 100), radius=180, fill=colour)
font = None
for f in ("/System/Library/Fonts/SFNSRounded.ttf", "/System/Library/Fonts/Supplemental/Arial Bold.ttf", "/System/Library/Fonts/Helvetica.ttc"):
    try:
        font = ImageFont.truetype(f, 520); break
    except OSError:
        pass
d.text((S / 2, S / 2 + 10), letter, fill="white", font=font, anchor="mm")
for px in (16, 32, 128, 256, 512):
    img.resize((px, px), Image.LANCZOS).save(out / f"icon_{px}x{px}.png")
    img.resize((px * 2, px * 2), Image.LANCZOS).save(out / f"icon_{px}x{px}@2x.png")
PY
  iconutil -c icns "$ICONS/$1.iconset" -o "$ICONS/$1.icns"
}

# make_app <App Name> <bundle id suffix> <letter> <colour> <script body>
make_app() {
  local name="$1" id="$2" letter="$3" colour="$4" body="$5"
  local app="$DEST/$name.app"
  rm -rf "$app"
  mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
  if [[ -f "$REPO/assets/icons/$id.icns" ]]; then
    cp "$REPO/assets/icons/$id.icns" "$app/Contents/Resources/icon.icns"   # designed icon (assets/icons/make_icons.py)
  else
    make_icon "$id" "$letter" "$colour"
    cp "$ICONS/$id.icns" "$app/Contents/Resources/icon.icns"
  fi
  cat > "$app/Contents/Info.plist" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>$name</string>
  <key>CFBundleDisplayName</key><string>$name</string>
  <key>CFBundleIdentifier</key><string>local.rimay.$id</string>
  <key>CFBundleExecutable</key><string>run</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSUIElement</key><true/>
</dict></plist>
PL
  cat > "$app/Contents/MacOS/run" <<SH
#!/bin/bash
# Generated by bin/make_apps.sh — edit that, not this.
REPO="$REPO"
PY="\$REPO/.venv/bin/python"
LOGS="$LOGS"
cd "\$REPO" || { osascript -e 'display alert "Rimay tools" message "Repo not found: $REPO — re-run bin/make_apps.sh"'; exit 1; }
fail() { osascript -e "display alert \"$name\" message \"\$1\""; exit 1; }
# serve <script> <port> <log>: start the server unless it already runs, wait for it, open it.
serve() {
  local url="http://127.0.0.1:\$2"
  if ! lsof -nP -iTCP:\$2 -sTCP:LISTEN >/dev/null 2>&1; then
    nohup "\$PY" "\$1" --no-browser --port "\$2" >>"\$LOGS/\$3" 2>&1 &
    for _ in \$(seq 1 40); do curl -fs "\$url" >/dev/null 2>&1 && break; sleep 0.25; done
    curl -fs "\$url" >/dev/null 2>&1 || fail "The server did not start. See outputs/_logs/\$3"
  fi
  open "\$url"
}
$body
SH
  chmod +x "$app/Contents/MacOS/run"
  touch "$app"
  echo "Created $app"
}

make_app "Rimay Curation" curation C "#2a78d6" 'serve scripts/curate.py 8765 curation-app.log'
make_app "Rimay Results" results R "#1baf7a" \
  '"$PY" scripts/build_dashboard.py >>"$LOGS/results-app.log" 2>&1 || fail "Building the dashboard failed. See outputs/_logs/results-app.log"
open "$REPO/outputs/dashboard.html"'
make_app "Rimay Anomalies" anomalies A "#eb6834" \
  '"$PY" scripts/build_anomalies.py --no-open >>"$LOGS/anomalies-app.log" 2>&1 || fail "Building the anomaly viewer failed. See outputs/_logs/anomalies-app.log"
open "$REPO/outputs/anomalies.html"'
make_app "Rimay Pragyan" pragyan P "#8a5cd6" 'serve scripts/pragyan.py 8766 pragyan-app.log'

rm -rf "$ICONS"
echo "Done. Open Finder → Go → Home → Applications, and drag the apps onto your Dock."
